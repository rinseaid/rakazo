import type { Duplex } from "node:stream";
import type Docker from "dockerode";
import { Hono } from "hono";
import { bodyLimit } from "hono/body-limit";
import { z } from "zod";
import {
  COMPUTER_USER,
  computerBridgeNameFor,
  computerResourceLimits,
  resolveComputerDns,
} from "./computer-spec.js";
import { processChannel, processFrames } from "./process-channel.js";
import { hasValidBearerToken, withKeyedLock } from "./supervisor-logic.js";

const MARKER = "rakazo.accountHost";
const MAX_LIFETIME_MS = 15 * 60_000;
const operations = ["model-login", "model-catalog", "model"] as const;
const ownerSchema = z.object({
  userId: z.string().min(1).max(256),
  spaceId: z.string().min(1).max(256),
  operationId: z.string().min(1).max(256),
  leaseId: z.uuid(),
});
const allocationSchema = ownerSchema
  .extend({
    operation: z.enum(operations),
    expiresAt: z.iso.datetime(),
  })
  .strict();
type Owner = z.infer<typeof ownerSchema>;
type Allocation = z.infer<typeof allocationSchema>;

export function accountHostName(leaseId: string) {
  return `rakazo-account-${z.uuid().parse(leaseId)}`;
}
function networkName(leaseId: string) {
  return `${accountHostName(leaseId)}-network`;
}
function labelsFor(input: Allocation) {
  return {
    "rakazo.managed": "true",
    [MARKER]: "1",
    "rakazo.userId": input.userId,
    "rakazo.spaceId": input.spaceId,
    "rakazo.operationId": input.operationId,
    "rakazo.leaseId": input.leaseId,
    "rakazo.operation": input.operation,
    "rakazo.expiresAt": input.expiresAt,
  };
}
export function accountHostOwned(labels: Record<string, string>, owner: Owner): boolean {
  return (
    labels[MARKER] === "1" &&
    Object.entries(owner).every(([key, value]) => labels[`rakazo.${key}`] === value)
  );
}
export function accountHostImageQualified(info: {
  Config?: { Labels?: Record<string, string>; Volumes?: Record<string, unknown> };
}): boolean {
  const labels = info.Config?.Labels ?? {};
  // Never start an image that declares implicit persistent/anonymous volumes.
  return (
    labels["rakazo.account-host.protocol"] === "1" &&
    labels["rakazo.account-host.qualified"] === "true" &&
    Object.keys(info.Config?.Volumes ?? {}).length === 0
  );
}
export function accountHostCreateOptions(
  input: Allocation,
  image: string,
): Docker.ContainerCreateOptions {
  const expires = Date.parse(input.expiresAt);
  return {
    name: accountHostName(input.leaseId),
    Image: image,
    User: COMPUTER_USER,
    WorkingDir: "/home/rakazo",
    Tty: false,
    AttachStdin: true,
    AttachStdout: true,
    AttachStderr: true,
    OpenStdin: true,
    StdinOnce: true,
    Entrypoint: ["/bin/sh", "-c"],
    // Numeric expiry is generated by us, not caller-provided shell content. Compute it at
    // start so an allocated-but-not-yet-started host cannot extend its absolute lease.
    Cmd: [
      `remaining=$(( ${expires} - $(date +%s%3N) )); [ "$remaining" -gt 0 ] || exit 125; exec python3 /usr/local/bin/rakazo-process "$remaining" /usr/local/bin/rakazo-acp-host --operation ${input.operation}`,
    ],
    Env: ["HOME=/home/rakazo", "PATH=/usr/local/bin:/usr/bin:/bin"],
    Labels: labelsFor(input),
    HostConfig: {
      ...computerResourceLimits(),
      Init: true,
      ReadonlyRootfs: true,
      Dns: resolveComputerDns(),
      NetworkMode: networkName(input.leaseId),
      CapDrop: ["ALL"],
      SecurityOpt: ["no-new-privileges:true"],
      RestartPolicy: { Name: "no" },
      Tmpfs: {
        "/tmp": "rw,nosuid,nodev,size=256m,mode=1777",
        "/home/rakazo": "rw,nosuid,nodev,size=16m,uid=1000,gid=1000,mode=700",
      },
      LogConfig: { Type: "none", Config: {} },
    },
  };
}
function gone(error: unknown) {
  return (error as { statusCode?: number })?.statusCode === 404;
}

export function createAccountHostRoutes(deps: {
  docker: Docker;
  image: string;
  token: string;
  withSpaceLock: <T>(spaceId: string, task: () => Promise<T>) => Promise<T>;
  countSpaceContainers: (spaceId: string) => Promise<number>;
  spaceLimit: () => number;
  prepareNetwork: () => Promise<void>;
}) {
  const app = new Hono();
  const locks = new Map<string, Promise<void>>();
  app.use("*", async (c, next) => {
    if (!hasValidBearerToken(c.req.header("authorization"), deps.token))
      return c.json({ error: "unauthorized" }, 401);
    await next();
  });
  app.use("*", async (c, next) => {
    if (c.req.method === "POST" && c.req.path.endsWith("/process")) return next();
    return bodyLimit({ maxSize: 8192 })(c, next);
  });
  app.onError(
    () =>
      new Response(JSON.stringify({ error: "Account host operation failed" }), {
        status: 400,
        headers: { "content-type": "application/json" },
      }),
  );
  const ownerFrom = (header: (key: string) => string | undefined): Owner =>
    ownerSchema.parse({
      userId: header("x-rakazo-user-id"),
      spaceId: header("x-rakazo-space-id"),
      operationId: header("x-rakazo-operation-id"),
      leaseId: header("x-rakazo-lease-id"),
    });
  const qualified = async () => {
    try {
      const image = await deps.docker.getImage(deps.image).inspect();
      return accountHostImageQualified(image) ? image.Id : undefined;
    } catch {
      return undefined;
    }
  };
  async function owned(id: string, owner: Owner) {
    if (id !== accountHostName(owner.leaseId)) throw new Error("Invalid account host");
    const container = deps.docker.getContainer(id);
    const info = await container.inspect();
    if (!accountHostOwned(info.Config.Labels ?? {}, owner))
      throw new Error("Invalid account host owner");
    // Resolve the immutable ID: a delayed start must not target a new container
    // that reused this lease name after cleanup.
    return { container: deps.docker.getContainer(info.Id), info };
  }
  async function optionalContainer(name: string) {
    try {
      return await deps.docker.getContainer(name).inspect();
    } catch (error) {
      if (!gone(error)) throw error;
      return undefined;
    }
  }
  async function assertOpen(owner: Owner, expiresAt: string) {
    const expiry = Date.parse(expiresAt);
    if (
      !Number.isFinite(expiry) ||
      expiry <= Date.now() ||
      (await optionalContainer(`${accountHostName(owner.leaseId)}-closed`))
    )
      throw new Error("Account host lease is closed");
  }
  app.get("/capabilities", async (c) => {
    const supported = Boolean(await qualified());
    return c.json({ supported, operations: supported ? [...operations] : [] });
  });
  app.post("/", async (c) => {
    const input = allocationSchema.parse(await c.req.json());
    const owner = ownerFrom((key) => c.req.header(key));
    if (!accountHostOwned(labelsFor(input), owner)) throw new Error("Invalid account host owner");
    const lifetime = Date.parse(input.expiresAt) - Date.now();
    if (lifetime <= 0 || lifetime > MAX_LIFETIME_MS) throw new Error("Invalid account host expiry");
    const image = await qualified();
    if (!image) return c.json({ error: "Account hosts unavailable" }, 409);
    await deps.prepareNetwork();
    return withKeyedLock(locks, owner.leaseId, () =>
      deps.withSpaceLock(input.spaceId, async () => {
        await assertOpen(owner, input.expiresAt);
        const limit = deps.spaceLimit();
        if (limit > 0 && (await deps.countSpaceContainers(input.spaceId)) >= limit)
          return c.json({ error: "Computer limit reached" }, 429);
        const network = await deps.docker.createNetwork({
          Name: networkName(input.leaseId),
          Driver: "bridge",
          CheckDuplicate: true,
          Labels: labelsFor(input),
          Options: {
            "com.docker.network.bridge.enable_icc": "false",
            "com.docker.network.bridge.name": computerBridgeNameFor(accountHostName(input.leaseId)),
          },
        });
        try {
          const container = await deps.docker.createContainer(
            accountHostCreateOptions(input, image),
          );
          try {
            await assertOpen(owner, input.expiresAt);
          } catch (error) {
            await container.remove({ force: true, v: true }).catch(() => undefined);
            throw error;
          }
        } catch (error) {
          // A lost Docker response may hide the container; never destroy a possibly live
          // allocation here. Its deterministic name and tagged expiry permit safe recovery.
          await network.remove().catch(() => undefined);
          throw error;
        }
        return c.json({ id: accountHostName(input.leaseId), expiresAt: input.expiresAt });
      }),
    );
  });
  app.post("/:id/process", async (c) => {
    const owner = ownerFrom((key) => c.req.header(key));
    if (!c.req.raw.body) throw new Error("Missing process input");
    const frames = processFrames(c.req.raw.body);
    z.object({ type: z.literal("start"), argv: z.array(z.never()).length(0) })
      .strict()
      .parse((await frames.next()).value);
    return withKeyedLock(locks, owner.leaseId, async () => {
      const { container, info } = await owned(c.req.param("id"), owner);
      const expiry = Date.parse(info.Config.Labels["rakazo.expiresAt"] ?? "");
      if (info.State.Status !== "created" || !Number.isFinite(expiry) || expiry <= Date.now())
        throw new Error("Account host lease unavailable");
      await assertOpen(owner, info.Config.Labels["rakazo.expiresAt"]!);
      c.req.raw.signal.throwIfAborted();
      // Docker container-name uniqueness is the durable single-launch fence, including
      // competing supervisors and restarts. Never start this marker container. A failed
      // launch remains claimed: no retry can silently repeat the account operation.
      const launch = await deps.docker.createContainer({
        name: `${accountHostName(owner.leaseId)}-launch`,
        Image: info.Image,
        Entrypoint: ["/bin/false"],
        Cmd: [],
        Labels: { ...info.Config.Labels, "rakazo.accountHostLaunch": "1" },
        HostConfig: { NetworkMode: "none", ReadonlyRootfs: true, RestartPolicy: { Name: "no" } },
      });
      try {
        await assertOpen(owner, info.Config.Labels["rakazo.expiresAt"]!);
      } catch (error) {
        await launch.remove({ force: true, v: true }).catch(() => undefined);
        throw error;
      }
      const stream = (await container.attach({
        stream: true,
        stdin: true,
        stdout: true,
        stderr: true,
        hijack: true,
      })) as Duplex;
      try {
        await container.start();
      } catch (error) {
        stream.destroy();
        throw error;
      }
      const inspector = { inspect: async () => (await container.inspect()).State };
      return new Response(processChannel(inspector, stream, frames, c.req.raw.signal), {
        headers: {
          "content-type": "application/x-ndjson",
          "cache-control": "no-store",
          // Inspect result of the immutable, owner-verified container, not a tag or caller label.
          "x-rakazo-account-image-id": info.Image,
        },
      });
    });
  });
  app.delete("/:id", async (c) => {
    const owner = ownerFrom((key) => c.req.header(key));
    const id = accountHostName(owner.leaseId);
    if (c.req.param("id") !== id) throw new Error("Invalid account host");
    const expiresAt = z.iso.datetime().parse(c.req.header("x-rakazo-expires-at"));
    if (Date.parse(expiresAt) > Date.now() + MAX_LIFETIME_MS)
      throw new Error("Invalid account host expiry");
    return withKeyedLock(locks, owner.leaseId, async () => {
      const validate = (labels: Record<string, string>) => {
        if (!accountHostOwned(labels, owner) || labels["rakazo.expiresAt"] !== expiresAt)
          throw new Error("Invalid account host owner or expiry");
      };
      const [host, launch, closed] = await Promise.all(
        [id, `${id}-launch`, `${id}-closed`].map(optionalContainer),
      );
      for (const resource of [host, launch, closed])
        if (resource) validate(resource.Config.Labels ?? {});
      const network = deps.docker.getNetwork(networkName(owner.leaseId));
      let networkInfo: Awaited<ReturnType<typeof network.inspect>> | undefined;
      try {
        networkInfo = await network.inspect();
        validate(networkInfo.Labels ?? {});
      } catch (error) {
        if (!gone(error)) throw error;
      }
      if (!closed) {
        let image = host?.Image ?? launch?.Image;
        if (!image) {
          const inspected = await deps.docker.getImage(deps.image).inspect();
          if (Object.keys(inspected.Config?.Volumes ?? {}).length)
            throw new Error("Account host image declares volumes");
          image = inspected.Id;
        }
        try {
          // A close tombstone survives DELETE so delayed POST/start requests cannot
          // create runnable work after the API has released its quota reservation.
          await deps.docker.createContainer({
            name: `${id}-closed`,
            Image: image,
            Entrypoint: ["/bin/false"],
            Cmd: [],
            Labels: {
              [MARKER]: "1",
              "rakazo.accountHostClosed": "1",
              "rakazo.expiresAt": expiresAt,
              ...Object.fromEntries(
                Object.entries(owner).map(([key, value]) => [`rakazo.${key}`, value]),
              ),
            },
            HostConfig: {
              NetworkMode: "none",
              ReadonlyRootfs: true,
              RestartPolicy: { Name: "no" },
            },
          });
        } catch (error) {
          if ((error as { statusCode?: number })?.statusCode !== 409) throw error;
          const existing = await optionalContainer(`${id}-closed`);
          if (!existing) throw error;
          validate(existing.Config.Labels ?? {});
        }
      }
      for (const resource of [host, launch])
        if (resource)
          await deps.docker
            .getContainer(resource.Id)
            .remove({ force: true, v: true })
            .catch((error) => {
              if (!gone(error)) throw error;
            });
      if (networkInfo)
        await deps.docker
          .getNetwork(networkInfo.Id)
          .remove()
          .catch((error) => {
            if (!gone(error)) throw error;
          });
      return c.json({ destroyed: true });
    });
  });
  async function sweep() {
    const now = Date.now();
    let incomplete = false;
    const containers = await deps.docker.listContainers({
      all: true,
      filters: { label: [`${MARKER}=1`] },
    });
    for (const item of containers) {
      if (item.Labels?.[MARKER] !== "1") continue;
      const expiry = Date.parse(item.Labels?.["rakazo.expiresAt"] ?? "");
      if (!Number.isFinite(expiry) || expiry <= now)
        await deps.docker
          .getContainer(item.Id)
          .remove({ force: true, v: true })
          .catch((error) => {
            if (!gone(error)) incomplete = true;
          });
    }
    const networks = await deps.docker.listNetworks({ filters: { label: [`${MARKER}=1`] } });
    for (const item of networks) {
      if (item.Labels?.[MARKER] !== "1") continue;
      const expiry = Date.parse(item.Labels?.["rakazo.expiresAt"] ?? "");
      if (!Number.isFinite(expiry) || expiry <= now)
        await deps.docker
          .getNetwork(item.Id)
          .remove()
          .catch((error) => {
            if (!gone(error)) incomplete = true;
          });
    }
    if (incomplete) throw new Error("Account host cleanup incomplete");
  }
  return { app, sweep };
}
